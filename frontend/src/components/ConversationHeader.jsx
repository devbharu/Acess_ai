import { memo, useState } from 'react';
import { Paperclip, FileDown } from 'lucide-react';
import LookupPopover from './LookupPopover';

function formatFileSize(bytes) {
  if (!bytes || isNaN(bytes)) return '';
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
}

/**
 * ConversationHeader
 * Displays conversation title on the left, and Media & Artifacts popover
 * trigger buttons arranged in the top right corner.
 */
function ConversationHeader({
  title,
  media = [],
  artifacts = [],
  mediaCount = 0,
}) {
  const [activePopover, setActivePopover] = useState(null); // 'media' | 'artifacts' | null

  const mediaList = Array.isArray(media) ? media : [];
  const artifactsList = Array.isArray(artifacts) ? artifacts : [];

  const mediaItems = mediaList.map((m) => {
    const isImage = m.kind === 'image';
    const metaParts = [isImage ? 'image' : 'document'];
    if (isImage) {
      metaParts.push(m.ocr_used ? 'AI Vision + OCR' : 'AI Vision Scene');
    } else {
      if (m.pages) metaParts.push(`${m.pages}p`);
      if (m.chars) metaParts.push(`${m.chars.toLocaleString()} chars`);
    }
    const content = isImage
      ? (m.image_description || 'Visual scene processed with AI vision model.')
      : (m.extracted_text || 'Document parsed with text extraction.');

    return {
      id: m.id,
      name: m.name,
      meta: `| ${metaParts.join(' · ')} |`,
      content,
      url: `/api/attachments/${m.id}/file`,
    };
  });

  const artifactItems = artifactsList.map((a) => {
    const metaParts = [a.kind || 'pdf'];
    const size = formatFileSize(a.file_size);
    if (size) metaParts.push(size);
    if (a.pages) metaParts.push(`${a.pages}p`);

    return {
      id: a.id,
      name: a.title,
      meta: `| ${metaParts.join(' · ')} |`,
      content: a.summary_text || 'Structured report generated by AccessAI.',
      url: a.download_url || a.view_url || `/api/artifacts/${a.id}/file`,
    };
  });

  const togglePopover = (type) => {
    setActivePopover((prev) => (prev === type ? null : type));
  };

  return (
    <header className="chat-head">
      <div className="chat-head-left">
        <h1>{title}</h1>
      </div>

      {/* Top right corner: Media and Artifacts triggers */}
      <div className="chat-head-right">
        {/* Media Button & Dedicated Media Popover */}
        <div className="lookup-popover-wrapper">
          <button
            type="button"
            className={`btn btn-sm lookup-trigger-btn ${activePopover === 'media' ? 'active' : ''}`}
            onClick={() => togglePopover('media')}
            aria-expanded={activePopover === 'media'}
            aria-label={`Media attached, ${mediaItems.length} files`}
            title="View files in this chat"
          >
            <Paperclip size={14} />
            <span>Media</span>
            <span className={`pill-counter ${mediaItems.length > 0 ? 'has-items' : ''}`}>
              {mediaItems.length}
            </span>
          </button>

          {activePopover === 'media' && (
            <LookupPopover
              title="Media"
              items={mediaItems}
              emptyMessage="No files attached to this chat yet."
              onClose={() => setActivePopover(null)}
              alignRight
            />
          )}
        </div>

        {/* Artifacts Button & Dedicated Artifacts Popover */}
        <div className="lookup-popover-wrapper">
          <button
            type="button"
            className={`btn btn-sm lookup-trigger-btn ${activePopover === 'artifacts' ? 'active' : ''}`}
            onClick={() => togglePopover('artifacts')}
            aria-expanded={activePopover === 'artifacts'}
            aria-label={`Generated artifacts, ${artifactItems.length} items`}
            title="View generated PDF reports and summaries"
          >
            <FileDown size={14} />
            <span>Artifacts</span>
            <span className={`pill-counter ${artifactItems.length > 0 ? 'has-items artifact-pill' : ''}`}>
              {artifactItems.length}
            </span>
          </button>

          {activePopover === 'artifacts' && (
            <LookupPopover
              title="Artifacts"
              items={artifactItems}
              emptyMessage="No artifacts generated in this chat yet."
              onClose={() => setActivePopover(null)}
              alignRight
            />
          )}
        </div>
      </div>
    </header>
  );
}

export default memo(ConversationHeader);
